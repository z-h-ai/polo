"""Regenerate the browsable token preview from the two authoritative token CSS files.

Output is deterministic (no timestamps): rerunning against unchanged inputs
must be byte-identical, which check_design_system.py relies on to prove the
preview never drifts from the maintained sources. Values shown in the browser
come from the real embedded CSS, not from copies inside this script.
"""
import hashlib
import re
from pathlib import Path

DESIGN = Path(__file__).resolve().parents[1]
BASE_CSS = DESIGN / 'assets/tokens/workbench-base.css'
REVIEW_CSS = DESIGN / 'assets/tokens/workbench-review.css'
OUT = DESIGN / 'assets/tokens/token-preview.html'


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def declarations(css_text):
    """Extract top-level custom property declarations as an ordered (name, value) list."""
    found = []
    for match in re.finditer(r'(--[a-z0-9-]+)\s*:\s*([^;{}]+);', css_text):
        found.append((match.group(1), match.group(2).strip()))
    return found


def block(css_text, selector_pattern):
    match = re.search(selector_pattern + r'\s*\{([\s\S]*?)\n?\}', css_text)
    return match.group(1) if match else ''


def font_sizes(css_text):
    sizes = []
    for match in re.finditer(r'font-size\s*:\s*([0-9.]+px)', css_text):
        size = match.group(1)
        if size not in sizes:
            sizes.append(size)
    return sizes


def breakpoints(css_text):
    found = []
    for match in re.finditer(r'@media\s*\(max-width\s*:\s*([0-9]+)px\)', css_text):
        value = match.group(1)
        if value not in found:
            found.append(value)
    return found


def swatch_rows(pairs):
    rows = []
    for name, value in pairs:
        if re.match(r'^#([0-9a-fA-F]{3,8})|rgba?\(', value):
            sample = ('<td class="swatch-cell"><span class="swatch" '
                      'style="background:%s"></span></td>' % value)
        else:
            sample = '<td class="swatch-cell"><span class="swatch swatch-derived"></span></td>'
        rows.append('<tr><td><code>%s</code></td><td><code>%s</code></td>%s</tr>'
                    % (name, value.replace('<', '&lt;'), sample))
    return '\n'.join(rows)


def material_samples(pairs):
    surfaces = [('canvas', '93% 背景'), ('list', '94% 表面'), ('reading', '99% 表面'),
                ('card', '98% 表面'), ('brand', '94% 近背景')]
    cells = []
    for name, note in surfaces:
        cells.append('<div class="material-surface" style="background:var(--client-material-%s);'
                     'backdrop-filter:blur(var(--client-material-blur))">'
                     '<strong>--client-material-%s</strong><span>%s · blur 24px</span></div>' % (name, name, note))
    table = swatch_rows([p for p in pairs if p[0].startswith('--client-material')])
    return '\n'.join(cells), table


